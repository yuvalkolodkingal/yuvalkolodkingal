#!/usr/bin/env python3
"""Build a terminal-style GitHub profile README from profile.toml.

    build.py init --username U [--name N]     write profile.toml, README, workflow
    build.py fetch [--no-token]                refresh data/ from GitHub
    build.py render [--only a,b] [--static]    write assets/*.svg
    build.py readme                            rewrite the marker blocks in README.md
    build.py all [--no-fetch]                  fetch, render, readme, check
    build.py check [--strict]                  validate config and every SVG
    build.py eject [--out DIR] [--update]      vendor this engine into the repo
    build.py list                              show the enabled panels
    build.py themes                            show the palettes

Run it from the profile repository root (the folder with profile.toml) or
pass --root. Exit codes: 0 ok, 1 usage or runtime error, 2 check failure,
3 config error. A network failure never fails the build; the fetchers keep
their previous cache and say so.
"""

