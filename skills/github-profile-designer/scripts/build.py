ALLOWED_NON_ASCII = set("…·●└─│├┌┐┘┬┴┼▁▂▃▄▅▆▇█░▒▓→←↑↓")


def cmd_check(build, args):
    errors = warnings = 0

    def error(message):
        nonlocal errors
        errors += 1
        print(f"error: {message}")

    def warn(message):
        nonlocal warnings
        warnings += 1
        print(f"warning: {message}")

    for theme in (build.dark, build.light):
        if theme is None:
            continue
        ratio = contrast(theme.fg, theme.bg)
        if ratio < 4.5:
            warn(f"{theme.name}: text contrast {ratio:.1f}:1 is under 4.5:1")

    svgs = sorted(build.assets.glob("*.svg"))
    if not svgs:
        warn(f"no SVGs in {build.assets}; run render first")
    for path in svgs:
        try:
            ET.parse(path)
        except ET.ParseError as exc:
            error(f"{path.name}: not well-formed XML ({exc})")
            continue
        text = path.read_text(encoding="utf-8")
        size = path.stat().st_size
        if "<script" in text:
            error(f"{path.name}: contains <script>; GitHub never runs it")
        if "<foreignObject" in text:
            error(f"{path.name}: contains <foreignObject>; renders blank inside <img>")
        body = re.sub(r'xmlns(:\w+)?="[^"]*"', "", text)
        body = re.sub(r'aria-label="[^"]*"', "", body)
        body = re.sub(r"<title>.*?</title>", "", body, flags=re.S)
        if re.search(r"@import|url\(\s*['\"]?https?:|href=\"https?:|href='https?:", body):
            error(f"{path.name}: references an external resource; it will not load inside <img>")
        animated = "<animate" in text or "@keyframes" in text
        if animated and "prefers-reduced-motion" not in text:
            error(f"{path.name}: animated but has no prefers-reduced-motion rule")
        odd = {c for c in re.sub(r"<[^>]+>", "", body) if ord(c) > 0x7E and c not in ALLOWED_NON_ASCII}
        if odd:
            warn(f"{path.name}: non-ASCII glyphs {''.join(sorted(odd))!r} may render as tofu in some fonts")
        if size > 300 * 1024:
            warn(f"{path.name}: {size // 1024} KB; keep SVGs under about 300 KB")
        elif not args.quiet:
            print(f"ok: {path.name} ({size // 1024} KB)")

    if build.readme.exists():
        text = build.readme.read_text(encoding="utf-8")
        for name in build.blocks():
            if BEGIN.format(name=name) not in text:
                warn(f"README has no block for {name}; run readme to insert it")
        for match in re.finditer(r'src="\./([^"]+)"', text):
            if not (build.root / match.group(1)).exists():
                error(f"README references missing file {match.group(1)}")
        if re.search(r"img\.shields\.io|github-readme-stats|streak-stats|readme-typing-svg|capsule-render", text):
            warn("README still loads images from a third-party service")
    else:
        warn("no README.md yet; run readme")

    print(f"check: {errors} error(s), {warnings} warning(s)")
    if errors or (args.strict and warnings):
        return 2
    return 0


def rewrite_engine_path(text, engine):
    """Point a workflow at a new engine folder.

    Workflows written from the template carry `# engine-path: <old>`; every
    occurrence of that path is replaced. Without the comment, path tokens
    ending in build.py or requirements.txt are re-rooted instead.
    """
    match = re.search(r"(?m)^# engine-path: (\S+)\s*$", text)
    if match:
        old = match.group(1)
        if old == engine:
            return text
        text = text.replace(old + "/", engine + "/").replace(old, engine)
        return text.replace(f"# engine-path: {old}", f"# engine-path: {engine}", 1) if f"# engine-path: {old}" in text else text
    return re.sub(
        r"(?<![\w/.-])(?:[\w./-]+/)?(build\.py|requirements\.txt)\b",
        lambda m: f"{engine}/{m.group(1)}",
        text,
    )


def cmd_eject(args):
    root = Path(args.root).resolve()
    out = (root / (args.out or "scripts/profile-engine")).resolve()
    if out.exists() and not args.update:
        print(f"{out} exists (use --update to refresh it)")
        return 1
    if out == HERE:
        print("the engine already lives in this repository; nothing to eject")
        return 0
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(HERE, out, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    (out / "VERSION").write_text(VERSION + "\n", encoding="utf-8")
    assets = out.parent / "profile-templates" if False else None  # templates stay with the skill
    print(f"copied the engine to {out.relative_to(root)} (version {VERSION})")
    workflow = root / ".github" / "workflows" / "profile.yml"
    engine = out.relative_to(root).as_posix()
    if workflow.exists():
        text = workflow.read_text(encoding="utf-8")
        new = rewrite_engine_path(text, engine)
        if new != text:
            workflow.write_text(new, encoding="utf-8")
            print(f"updated engine paths in {workflow.relative_to(root)}")
    else:
        template = (TEMPLATES / "workflow.template.yml").read_text(encoding="utf-8")
        workflow.parent.mkdir(parents=True, exist_ok=True)
        workflow.write_text(template.replace("{{engine}}", engine), encoding="utf-8")
        print(f"wrote {workflow.relative_to(root)} (engine path {engine})")
    print(f"daily builds now run python {engine}/build.py all without the skill installed")
    return 0


