def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", default=".", help="profile repository root (default: current directory)")
    parser.add_argument("--profile", default="profile.toml", help="config file, relative to --root")
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("init", help="scaffold profile.toml, README.md and the workflow")
    p.add_argument("--username", help="GitHub login")
    p.add_argument("--name", help="display name")
    p.add_argument("--palette", help="theme name (see themes)")
    p.add_argument("--force", action="store_true")
    p.add_argument("--no-workflow", action="store_true")
    p.add_argument("--no-eject", action="store_true", help="do not vendor the engine into the repository")

    p = sub.add_parser("fetch", help="refresh data/ from GitHub")
    p.add_argument("--no-token", action="store_true")

    p = sub.add_parser("render", help="write the SVG panels")
    p.add_argument("--only", help="comma-separated panel names")
    p.add_argument("--static", action="store_true", help="no animation (for previews)")

    sub.add_parser("readme", help="rewrite the marker blocks in README.md")

    p = sub.add_parser("all", help="fetch, render, readme, check")
    p.add_argument("--no-token", action="store_true")
    p.add_argument("--no-fetch", "--offline", action="store_true", dest="no_fetch")
    p.add_argument("--static", action="store_true")

    p = sub.add_parser("check", help="validate the config, the SVGs and the README")
    p.add_argument("--strict", action="store_true", help="warnings fail too")
    p.add_argument("--quiet", action="store_true")

    p = sub.add_parser("eject", help="vendor the engine into this repository")
    p.add_argument("--out", help="destination folder (default scripts/profile-engine)")
    p.add_argument("--update", action="store_true")

    sub.add_parser("list", help="show the enabled panels")
    sub.add_parser("themes", help="show the palettes")

    args = parser.parse_args(argv)
    if args.command == "themes":
        return cmd_themes(args)
    if args.command == "init":
        return cmd_init(args)
    if args.command == "eject":
        return cmd_eject(args)

    try:
        config = profile_config.load(Path(args.root) / args.profile)
    except profile_config.ConfigError as exc:
        print(f"error: {exc}")
        return 3
    build = Build(args.root, config, static=getattr(args, "static", False))

    if args.command == "fetch":
        return cmd_fetch(build, args)
    if args.command == "render":
        return cmd_render(build, args)
    if args.command == "readme":
        return cmd_readme(build, args)
    if args.command == "check":
        return cmd_check(build, args)
    if args.command == "list":
        return cmd_list(build, args)
    if args.command == "all":
        if not args.no_fetch:
            cmd_fetch(build, args)
        args.only = None
        cmd_render(build, args)
        cmd_readme(build, args)
        args.strict = False
        args.quiet = True
        return cmd_check(build, args)
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
